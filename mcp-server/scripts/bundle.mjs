// Bundles the server (and the workspace packages it imports) into dist/main.js.
// npm dependencies stay external and are installed in the container image.
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
const external = Object.keys(pkg.dependencies).filter((d) => !d.startsWith("@collections/"));

await build({
  entryPoints: ["src/main.ts"],
  outfile: "dist/main.js",
  bundle: true,
  platform: "node",
  target: "node20",
  format: "esm",
  sourcemap: true,
  external,
  banner: { js: "// Collections MCP server – generated by scripts/bundle.mjs" },
});
// Runtime manifest for the container: only the external npm dependencies.
const runtime = {
  name: "collections-mcp-runtime",
  private: true,
  type: "module",
  main: "main.js",
  engines: pkg.engines ?? { node: ">=20" },
  dependencies: Object.fromEntries(external.map((d) => [d, pkg.dependencies[d]])),
};
writeFileSync(new URL("../dist/package.json", import.meta.url), JSON.stringify(runtime, null, 2) + "\n");
console.log("dist/main.js and dist/package.json written");
